// Map MINGW/MSYS2 pkgbases to vcpkg ports (by normalized name). Ports read from C:/src/third_party/vcpkg (source of truth).
import { readdirSync, existsSync } from "node:fs";
import { join } from "node:path";
const ROOT = join(import.meta.dir, "..");
const PORTS = process.env.VCPKG_PORTS ?? "C:/src/third_party/vcpkg/ports";
const ports = existsSync(PORTS) ? readdirSync(PORTS) : [];
const norm = (s: string) => s.toLowerCase().replace(/^mingw-w64-/, "").replace(/[-_.]/g, "");
const idx = new Map<string, string>();
for (const p of ports) { idx.set(norm(p), p); if (p.startsWith("lib")) idx.set(norm(p.slice(3)), p); }
const g = await Bun.file(join(ROOT, "graph", "graph.json")).json();
const bases = [...new Set<string>(g.nodes.map((n: any) => n.base))].sort();
const rows: [string, string][] = [];
for (const b of bases) { const n = norm(b); const hit = idx.get(n) ?? idx.get(n.replace(/^lib/, "")) ?? (n.startsWith("python") ? undefined : idx.get("lib" + n)); if (hit) rows.push([b, hit]); }
let md = `# PKGBUILD -> vcpkg port\n\nGenerated by \`tools/vcpkg-map.ts\` (name heuristic, verify before use). Ports: \`${PORTS}\` (${ports.length}). Matches: ${rows.length}/${bases.length} pkgbases.\n\n| pkgbase | vcpkg port |\n|---|---|\n`;
md += rows.map(([a, b]) => `| ${a} | ${b} |`).join("\n") + "\n";
await Bun.write(join(ROOT, "vcpkg", "MAPPING.md"), md);
await Bun.write(join(ROOT, "vcpkg", "mapping.json"), JSON.stringify(Object.fromEntries(rows), null, 1));
console.log(JSON.stringify({ ports: ports.length, pkgbases: bases.length, mapped: rows.length }));
