// Cross-ecosystem map: top N pkgbases by reverse-dependency count (graph/graph.json) ->
// pacman pkgbase/repo, vcpkg port, winget id, NuGet id, PSGallery module.
// Sources: formats/vcpkg/mapping.json, $SRC_ROOT/third_party/winget-pkgs (git tree, no checkout needed),
// NuGet flatcontainer + PSGallery OData (exact id probes, cached in formats/xmap/cache.json; --offline skips network).
// Output: formats/xmap/{xmap.json,XMAP.md}. Overrides: formats/xmap/overrides.toml.
import { join } from "node:path";
import { readdirSync, existsSync } from "node:fs";
import { ROOT, SRC } from "./lib/identity.ts";
const N = Number(process.env.XMAP_TOP ?? 300), OFFLINE = process.argv.includes("--offline");
const OUT = join(ROOT, "formats", "xmap");
const g = await Bun.file(join(ROOT, "graph", "graph.json")).json();
const baseOf = new Map<string, string>(g.nodes.map((n: any) => [n.id, n.base]));
const rdeps = new Map<string, Set<string>>();
for (const e of g.edges) {
  const f = baseOf.get(e.from), t = baseOf.get(e.to);
  if (f && t && f !== t) (rdeps.get(t) ?? rdeps.set(t, new Set()).get(t)!).add(f);
}
const real = (b: string) => b.replace(/^mingw-w64-/, "");
// merge msys/mingw pkgbases with the same real name (e.g. zlib + mingw-w64-zlib)
const agg = new Map<string, { bases: Set<string>; rd: Set<string> }>();
for (const [b, s] of rdeps) { const k = real(b); const a = agg.get(k) ?? agg.set(k, { bases: new Set(), rd: new Set() }).get(k)!; a.bases.add(b); for (const x of s) a.rd.add(real(x)); }
const top = [...agg].sort((a, b) => b[1].rd.size - a[1].rd.size || a[0].localeCompare(b[0])).slice(0, N);

const repoOf = new Map<string, string>();
for (const r of ["core", "extra", "mingw"]) for (const d of readdirSync(join(ROOT, "repos", r))) repoOf.set(d, r);
const vcpkg: Record<string, string> = await Bun.file(join(ROOT, "formats", "vcpkg", "mapping.json")).json();
const ov: Record<string, Record<string, string>> = Bun.TOML.parse(await Bun.file(join(OUT, "overrides.toml")).text()) as any;

// winget index: manifests/<l>/<Publisher>/<Name> -> Publisher.Name
const norm = (s: string) => s.toLowerCase().replace(/^lib/, "").replace(/[-_.+]/g, "");
const wg = new Map<string, string[]>();
const WP = join(SRC, "third_party", "winget-pkgs");
if (existsSync(WP)) {
  const out = await Bun.$`git -C ${WP} ls-tree -r -d --name-only HEAD manifests`.quiet().text();
  for (const l of out.split("\n")) { const p = l.split("/"); if (p.length !== 4) continue; const id = `${p[2]}.${p[3]}`; const k = norm(p[3]); (wg.get(k) ?? wg.set(k, []).get(k)!).push(id); }
}
const pickWinget = (k: string) => { const c = wg.get(norm(k)); if (!c) return ""; return c.find((id) => norm(id.split(".")[0]) === norm(k)) ?? ""; };

const cacheF = join(OUT, "cache.json");
const cache: Record<string, boolean> = existsSync(cacheF) ? await Bun.file(cacheF).json() : {};
async function probe(kind: "nuget" | "ps", id: string) {
  const key = `${kind}:${id.toLowerCase()}`;
  if (key in cache || OFFLINE) return cache[key] ?? false;
  try {
    const r = kind === "nuget"
      ? await fetch(`https://api.nuget.org/v3-flatcontainer/${id.toLowerCase()}/index.json`, { method: "HEAD" })
      : await fetch(`https://www.powershellgallery.com/api/v2/FindPackagesById()?id='${encodeURIComponent(id)}'`);
    cache[key] = kind === "nuget" ? r.ok : r.ok && (await r.text()).includes("<entry>");
  } catch { return false; }
  return cache[key];
}
type Row = { rank: number; name: string; rdeps: number; pkgbases: string[]; repo: string; vcpkg: string; winget: string; nuget: string; psgallery: string; heuristic: string[] };
const rows: Row[] = [];
const work = top.map(([k, a], i) => async () => {
  const o = ov[k] ?? {}, h: string[] = [];
  const bases = [...a.bases].sort();
  const vp = o.vcpkg ?? bases.map((b) => vcpkg[b]).find(Boolean) ?? ""; if (vp && o.vcpkg === undefined) h.push("vcpkg");
  const w = o.winget ?? pickWinget(k); if (w && o.winget === undefined) h.push("winget");
  const nu = o.nuget ?? ((await probe("nuget", k)) ? k : ""); if (nu && o.nuget === undefined) h.push("nuget");
  const ps = o.psgallery ?? ((await probe("ps", k)) ? k : ""); if (ps && o.psgallery === undefined) h.push("psgallery");
  rows[i] = { rank: i + 1, name: k, rdeps: a.rd.size, pkgbases: bases, repo: [...new Set(bases.map((b) => repoOf.get(b.replace(/[^\w.+-]/g, "_")) ?? "?"))].join("+"), vcpkg: vp, winget: w, nuget: nu, psgallery: ps, heuristic: h };
});
for (let i = 0; i < work.length; i += 8) await Promise.all(work.slice(i, i + 8).map((f) => f()));
if (!OFFLINE) await Bun.write(cacheF, JSON.stringify(cache, null, 0));
await Bun.write(join(OUT, "xmap.json"), JSON.stringify(rows, null, 1));
const cnt = (f: keyof Row) => rows.filter((r) => r[f]).length;
let md = `# Cross-ecosystem map (top ${rows.length} by reverse deps)\n\nGenerated by \`tools/xmap.ts\` (\`just xmap\`). Name matches marked \`*\` are heuristics: verify before use, fix in \`overrides.toml\`. Coverage: vcpkg ${cnt("vcpkg")}, winget ${cnt("winget")}, NuGet ${cnt("nuget")}, PSGallery ${cnt("psgallery")}.\n\n| # | name | rdeps | pacman pkgbase(s) | repo | vcpkg port | winget id | NuGet id | PSGallery |\n|---|---|---|---|---|---|---|---|---|\n`;
const s = (r: Row, f: "vcpkg" | "winget" | "nuget" | "psgallery") => (r[f] ? r[f] + (r.heuristic.includes(f) ? "*" : "") : "");
md += rows.map((r) => `| ${r.rank} | ${r.name} | ${r.rdeps} | ${r.pkgbases.join(", ")} | ${r.repo} | ${s(r, "vcpkg")} | ${s(r, "winget")} | ${s(r, "nuget")} | ${s(r, "psgallery")} |`).join("\n") + "\n";
await Bun.write(join(OUT, "XMAP.md"), md);
console.log(JSON.stringify({ rows: rows.length, vcpkg: cnt("vcpkg"), winget: cnt("winget"), nuget: cnt("nuget"), psgallery: cnt("psgallery"), wingetIndex: wg.size }));
